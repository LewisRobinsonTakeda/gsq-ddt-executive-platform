import type { Site } from './site-model';

export const FreshnessFreshnessStatusKeyToLabel = {
  'Current': 'Current',
  'DueSoon': 'Due Soon',
  'Stale': 'Stale',
  'Unavailable': 'Unavailable'
} as const;
export type FreshnessFreshnessStatusKey = keyof typeof FreshnessFreshnessStatusKeyToLabel;

export const FreshnessSourceOwnerRoleKeyToLabel = {
  'DigitalDelivery': 'Digital Delivery',
  'SitePortfolio': 'Site Portfolio',
  'EnterpriseData': 'Enterprise Data',
  'ContentEditor': 'Content Editor'
} as const;
export type FreshnessSourceOwnerRoleKey = keyof typeof FreshnessSourceOwnerRoleKeyToLabel;

export const FreshnessSourceSystemKeyToLabel = {
  'Jira': 'Jira',
  'SPOT': 'SPOT',
  'EDB': 'EDB',
  'SharePoint': 'SharePoint'
} as const;
export type FreshnessSourceSystemKey = keyof typeof FreshnessSourceSystemKeyToLabel;

export interface Freshness {
  /**
   * @displayName Freshness ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Freshness Record Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  freshnessRecordName: string;
  /**
   * @displayName Data Domain
   * @validationRule Required for create/update operations
   */
  dataDomain: string;
  /**
   * @displayName Freshness Status
   * @validationRule Required for create/update operations
   */
  freshnessStatusKey: FreshnessFreshnessStatusKey;
  /**
   * @displayName Integration Needed
   * @validationRule Required for create/update operations
   */
  integrationNeeded: boolean;
  /**
   * @displayName Last Refreshed Date
   * @validationRule Required for create/update operations
   */
  lastRefreshedDate: string;
  /**
   * @displayName Site
   * @validationRule Required for create/update operations
   */
  site: Pick<Site, 'id' | 'name1'>;
  /**
   * @displayName Source Owner Role
   * @validationRule Required for create/update operations
   */
  sourceOwnerRoleKey: FreshnessSourceOwnerRoleKey;
  /**
   * @displayName Source System
   * @validationRule Required for create/update operations
   */
  sourceSystemKey: FreshnessSourceSystemKey;
}

export const _Freshness = 'Freshness' as const;
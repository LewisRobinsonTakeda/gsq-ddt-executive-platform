import type { UserSiteRole } from './user-site-role-model';

export const AuditActionKeyToLabel = {
  'Created': 'Created',
  'Updated': 'Updated',
  'Reviewed': 'Reviewed',
  'Approved': 'Approved',
  'Accessed': 'Accessed'
} as const;
export type AuditActionKey = keyof typeof AuditActionKeyToLabel;

export const AuditEntityTableKeyToLabel = {
  'Projects': 'Projects',
  'Risks': 'Risks',
  'Commentary': 'Commentary',
  'Financials': 'Financials',
  'ReviewFreeze': 'ReviewFreeze'
} as const;
export type AuditEntityTableKey = keyof typeof AuditEntityTableKeyToLabel;

export interface Audit {
  /**
   * @displayName Audit ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Audit Event Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  auditEventName: string;
  /**
   * @displayName Action
   * @validationRule Required for create/update operations
   */
  actionKey: AuditActionKey;
  /**
   * @displayName Details
   * @validationRule Required for create/update operations
   */
  details: string;
  /**
   * @displayName Entity Table
   * @validationRule Required for create/update operations
   */
  entityTableKey: AuditEntityTableKey;
  /**
   * @displayName Occurred Date
   * @validationRule Required for create/update operations
   */
  occurredDate: string;
  /**
   * @displayName Record Reference
   * @validationRule Required for create/update operations
   */
  recordReference: string;
  /**
   * @displayName User Site Role
   * @validationRule Required for create/update operations
   */
  userSiteRole: Pick<UserSiteRole, 'id' | 'userSiteRoleName'>;
}

export const _Audit = 'Audit' as const;
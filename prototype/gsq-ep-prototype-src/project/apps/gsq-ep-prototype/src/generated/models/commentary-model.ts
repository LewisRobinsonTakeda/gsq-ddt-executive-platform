import type { Site } from './site-model';

export const CommentaryCategoryKeyToLabel = {
  'ExecutiveSummary': 'Executive Summary',
  'Progress': 'Progress',
  'Constraint': 'Constraint',
  'Decision': 'Decision'
} as const;
export type CommentaryCategoryKey = keyof typeof CommentaryCategoryKeyToLabel;

export const CommentaryEntrySourceKeyToLabel = {
  'SharePoint': 'SharePoint'
} as const;
export type CommentaryEntrySourceKey = keyof typeof CommentaryEntrySourceKeyToLabel;

export const CommentaryPublicationStatusKeyToLabel = {
  'Draft': 'Draft',
  'InReview': 'In Review',
  'Approved': 'Approved',
  'Published': 'Published',
  'Archived': 'Archived'
} as const;
export type CommentaryPublicationStatusKey = keyof typeof CommentaryPublicationStatusKeyToLabel;

export interface Commentary {
  /**
   * @displayName Commentary ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Commentary Title
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  commentaryTitle: string;
  /**
   * @displayName Approval Comments
   */
  approvalComments?: string;
  /**
   * @displayName Category
   * @validationRule Required for create/update operations
   */
  categoryKey: CommentaryCategoryKey;
  /**
   * @displayName Commentary
   * @validationRule Required for create/update operations
   */
  commentary: string;
  /**
   * @displayName Created Date
   * @validationRule Required for create/update operations
   */
  createdDate: string;
  /**
   * @displayName Entry Source
   * @validationRule Required for create/update operations
   */
  entrySourceKey: CommentaryEntrySourceKey;
  /**
   * @displayName Publication Status
   * @validationRule Required for create/update operations
   */
  publicationStatusKey: CommentaryPublicationStatusKey;
  /**
   * @displayName Reviewed Date
   */
  reviewedDate?: string;
  /**
   * @displayName Site
   * @validationRule Required for create/update operations
   */
  site: Pick<Site, 'id' | 'name1'>;
}

export const _Commentary = 'Commentary' as const;
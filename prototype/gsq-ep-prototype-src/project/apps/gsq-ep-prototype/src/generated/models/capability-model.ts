import type { Site } from './site-model';

export const CapabilityCapabilityStatusKeyToLabel = {
  'NotStarted': 'Not Started',
  'InProgress': 'In Progress',
  'Established': 'Established',
  'NeedsAttention': 'Needs Attention'
} as const;
export type CapabilityCapabilityStatusKey = keyof typeof CapabilityCapabilityStatusKeyToLabel;

export const CapabilityEDBSourceOwnerRoleKeyToLabel = {
  'EnterpriseData': 'Enterprise Data',
  'SiteDataLead': 'Site Data Lead',
  'DigitalDelivery': 'Digital Delivery'
} as const;
export type CapabilityEDBSourceOwnerRoleKey = keyof typeof CapabilityEDBSourceOwnerRoleKeyToLabel;

export const CapabilityMaturityLevelKeyToLabel = {
  'Initial': 'Initial',
  'Developing': 'Developing',
  'Defined': 'Defined',
  'Managed': 'Managed',
  'Optimized': 'Optimized'
} as const;
export type CapabilityMaturityLevelKey = keyof typeof CapabilityMaturityLevelKeyToLabel;

export interface Capability {
  /**
   * @displayName Capability ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Capability Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  capabilityName: string;
  /**
   * @displayName Capability Status
   * @validationRule Required for create/update operations
   */
  capabilityStatusKey: CapabilityCapabilityStatusKey;
  /**
   * @displayName EDB Domain
   * @validationRule Required for create/update operations
   */
  eDBDomain: string;
  /**
   * @displayName EDB Integration Needed
   * @validationRule Required for create/update operations
   */
  eDBIntegrationNeeded: boolean;
  /**
   * @displayName EDB Source Owner Role
   * @validationRule Required for create/update operations
   */
  eDBSourceOwnerRoleKey: CapabilityEDBSourceOwnerRoleKey;
  /**
   * @displayName Gap Summary
   * @validationRule Required for create/update operations
   */
  gapSummary: string;
  /**
   * @displayName Maturity Level
   * @validationRule Required for create/update operations
   */
  maturityLevelKey: CapabilityMaturityLevelKey;
  /**
   * @displayName Site
   * @validationRule Required for create/update operations
   */
  site: Pick<Site, 'id' | 'name1'>;
}

export const _Capability = 'Capability' as const;
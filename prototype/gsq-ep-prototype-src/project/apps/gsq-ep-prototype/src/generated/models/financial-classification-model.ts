import type { Project } from './project-model';
import type { Site } from './site-model';

export const FinancialClassificationInvestmentClassificationKeyToLabel = {
  'NonInvestmentOperational': 'Non-Investment / Operational',
  'Investment': 'Investment'
} as const;
export type FinancialClassificationInvestmentClassificationKey = keyof typeof FinancialClassificationInvestmentClassificationKeyToLabel;

export const FinancialClassificationRecordStatusKeyToLabel = {
  'Draft': 'Draft',
  'Validated': 'Validated',
  'Approved': 'Approved',
  'Archived': 'Archived'
} as const;
export type FinancialClassificationRecordStatusKey = keyof typeof FinancialClassificationRecordStatusKeyToLabel;

export const FinancialClassificationSPOTSourceOwnerRoleKeyToLabel = {
  'SitePortfolio': 'Site Portfolio',
  'FinanceGovernance': 'Finance Governance',
  'DigitalDelivery': 'Digital Delivery'
} as const;
export type FinancialClassificationSPOTSourceOwnerRoleKey = keyof typeof FinancialClassificationSPOTSourceOwnerRoleKeyToLabel;

export interface FinancialClassification {
  /**
   * @displayName Financial Classification ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Financial Classification Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  financialClassificationName: string;
  /**
   * @displayName Investment Classification
   * @validationRule Required for create/update operations
   */
  investmentClassificationKey: FinancialClassificationInvestmentClassificationKey;
  /**
   * @displayName Project
   * @validationRule Required for create/update operations
   */
  project: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Record Status
   * @validationRule Required for create/update operations
   */
  recordStatusKey: FinancialClassificationRecordStatusKey;
  /**
   * @displayName Site
   * @validationRule Required for create/update operations
   */
  site: Pick<Site, 'id' | 'name1'>;
  /**
   * @displayName SPOT ID
   * @validationRule Required for create/update operations
   */
  sPOTID: string;
  /**
   * @displayName SPOT Integration Needed
   * @validationRule Required for create/update operations
   */
  sPOTIntegrationNeeded: boolean;
  /**
   * @displayName SPOT Source Owner Role
   * @validationRule Required for create/update operations
   */
  sPOTSourceOwnerRoleKey: FinancialClassificationSPOTSourceOwnerRoleKey;
}


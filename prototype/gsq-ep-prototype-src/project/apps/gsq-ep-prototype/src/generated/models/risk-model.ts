import type { Project } from './project-model';
import type { Site } from './site-model';

export const RiskEntrySourceKeyToLabel = {
  'SharePoint': 'SharePoint'
} as const;
export type RiskEntrySourceKey = keyof typeof RiskEntrySourceKeyToLabel;

export const RiskLikelihoodKeyToLabel = {
  'Unlikely': 'Unlikely',
  'Possible': 'Possible',
  'Likely': 'Likely',
  'AlmostCertain': 'Almost Certain'
} as const;
export type RiskLikelihoodKey = keyof typeof RiskLikelihoodKeyToLabel;

export const RiskRiskStatusKeyToLabel = {
  'Draft': 'Draft',
  'InReview': 'In Review',
  'Accepted': 'Accepted',
  'Mitigating': 'Mitigating',
  'Closed': 'Closed'
} as const;
export type RiskRiskStatusKey = keyof typeof RiskRiskStatusKeyToLabel;

export const RiskSeverityKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High',
  'Critical': 'Critical'
} as const;
export type RiskSeverityKey = keyof typeof RiskSeverityKeyToLabel;

export interface Risk {
  /**
   * @displayName Risk ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Risk Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  riskName: string;
  /**
   * @displayName Created Date
   * @validationRule Required for create/update operations
   */
  createdDate: string;
  /**
   * @displayName Entry Source
   * @validationRule Required for create/update operations
   */
  entrySourceKey: RiskEntrySourceKey;
  /**
   * @displayName Likelihood
   * @validationRule Required for create/update operations
   */
  likelihoodKey: RiskLikelihoodKey;
  /**
   * @displayName Project
   */
  project?: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Review Comments
   */
  reviewComments?: string;
  /**
   * @displayName Reviewed Date
   */
  reviewedDate?: string;
  /**
   * @displayName Risk Description
   * @validationRule Required for create/update operations
   */
  riskDescription: string;
  /**
   * @displayName Risk Status
   * @validationRule Required for create/update operations
   */
  riskStatusKey: RiskRiskStatusKey;
  /**
   * @displayName Severity
   * @validationRule Required for create/update operations
   */
  severityKey: RiskSeverityKey;
  /**
   * @displayName Site
   * @validationRule Required for create/update operations
   */
  site: Pick<Site, 'id' | 'name1'>;
}

export const _Risk = 'Risk' as const;
import type { BigRock } from './big-rock-model';
import type { Site } from './site-model';

export const StatusMapExecutiveStatusKeyToLabel = {
  'NotStarted': 'Not Started',
  'OnTrack': 'On Track',
  'AtRisk': 'At Risk',
  'OffTrack': 'Off Track',
  'Completed': 'Completed'
} as const;
export type StatusMapExecutiveStatusKey = keyof typeof StatusMapExecutiveStatusKeyToLabel;

export const StatusMapRoadmapYearBandKeyToLabel = {
  'FY26BUILDFOUNDATION': 'FY26 BUILD FOUNDATION',
  'FY27SCALEANDINTEGRATE': 'FY27 SCALE AND INTEGRATE',
  'FY28TRANSFORM': 'FY28+ TRANSFORM'
} as const;
export type StatusMapRoadmapYearBandKey = keyof typeof StatusMapRoadmapYearBandKeyToLabel;

export interface StatusMap {
  /**
   * @displayName Status Map ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Status Map Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  statusMapName: string;
  /**
   * @displayName Big Rock
   * @validationRule Required for create/update operations
   */
  bigRock: Pick<BigRock, 'id' | 'bigRockName'>;
  /**
   * @displayName Executive Status
   * @validationRule Required for create/update operations
   */
  executiveStatusKey: StatusMapExecutiveStatusKey;
  /**
   * @displayName Roadmap Year Band
   * @validationRule Required for create/update operations
   */
  roadmapYearBandKey: StatusMapRoadmapYearBandKey;
  /**
   * @displayName Site
   * @validationRule Required for create/update operations
   */
  site: Pick<Site, 'id' | 'name1'>;
  /**
   * @displayName Status Summary
   * @validationRule Required for create/update operations
   */
  statusSummary: string;
  /**
   * @displayName Updated Date
   * @validationRule Required for create/update operations
   */
  updatedDate: string;
}

export const _StatusMap = 'StatusMap' as const;
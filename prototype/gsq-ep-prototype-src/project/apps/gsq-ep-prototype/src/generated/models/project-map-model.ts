import type { BigRock } from './big-rock-model';
import type { Project } from './project-model';

export const ProjectMapMappingStatusKeyToLabel = {
  'Draft': 'Draft',
  'Validated': 'Validated',
  'Approved': 'Approved',
  'Archived': 'Archived'
} as const;
export type ProjectMapMappingStatusKey = keyof typeof ProjectMapMappingStatusKeyToLabel;

export const ProjectMapRoadmapYearBandKeyToLabel = {
  'FY26BUILDFOUNDATION': 'FY26 BUILD FOUNDATION',
  'FY27SCALEANDINTEGRATE': 'FY27 SCALE AND INTEGRATE',
  'FY28TRANSFORM': 'FY28+ TRANSFORM'
} as const;
export type ProjectMapRoadmapYearBandKey = keyof typeof ProjectMapRoadmapYearBandKeyToLabel;

export interface ProjectMap {
  /**
   * @displayName Project Map ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Project Map Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  projectMapName: string;
  /**
   * @displayName Big Rock
   * @validationRule Required for create/update operations
   */
  bigRock: Pick<BigRock, 'id' | 'bigRockName'>;
  /**
   * @displayName Mapping Status
   * @validationRule Required for create/update operations
   */
  mappingStatusKey: ProjectMapMappingStatusKey;
  /**
   * @displayName Project
   * @validationRule Required for create/update operations
   */
  project: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Roadmap Year Band
   * @validationRule Required for create/update operations
   */
  roadmapYearBandKey: ProjectMapRoadmapYearBandKey;
  /**
   * @displayName Sequence
   * @validationRule Required for create/update operations
   */
  sequence: number;
}

export const _ProjectMap = 'ProjectMap' as const;
import type { Site } from './site-model';

export const IntegrationIntegrationStatusKeyToLabel = {
  'NotPlanned': 'Not Planned',
  'Planned': 'Planned',
  'InProgress': 'In Progress',
  'Connected': 'Connected',
  'Blocked': 'Blocked'
} as const;
export type IntegrationIntegrationStatusKey = keyof typeof IntegrationIntegrationStatusKeyToLabel;

export const IntegrationSourceOwnerRoleKeyToLabel = {
  'DigitalDelivery': 'Digital Delivery',
  'SitePortfolio': 'Site Portfolio',
  'EnterpriseData': 'Enterprise Data'
} as const;
export type IntegrationSourceOwnerRoleKey = keyof typeof IntegrationSourceOwnerRoleKeyToLabel;

export const IntegrationSourceSystemKeyToLabel = {
  'Jira': 'Jira',
  'SPOT': 'SPOT',
  'EDB': 'EDB'
} as const;
export type IntegrationSourceSystemKey = keyof typeof IntegrationSourceSystemKeyToLabel;

export interface Integration {
  /**
   * @displayName Integration ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Integration Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  integrationName: string;
  /**
   * @displayName Data Domain
   * @validationRule Required for create/update operations
   */
  dataDomain: string;
  /**
   * @displayName Integration Needed
   * @validationRule Required for create/update operations
   */
  integrationNeeded: boolean;
  /**
   * @displayName Integration Status
   * @validationRule Required for create/update operations
   */
  integrationStatusKey: IntegrationIntegrationStatusKey;
  /**
   * @displayName Ownership Notes
   */
  ownershipNotes?: string;
  /**
   * @displayName Site
   * @validationRule Required for create/update operations
   */
  site: Pick<Site, 'id' | 'name1'>;
  /**
   * @displayName Source Owner Role
   * @validationRule Required for create/update operations
   */
  sourceOwnerRoleKey: IntegrationSourceOwnerRoleKey;
  /**
   * @displayName Source System
   * @validationRule Required for create/update operations
   */
  sourceSystemKey: IntegrationSourceSystemKey;
}

export const _Integration = 'Integration' as const;
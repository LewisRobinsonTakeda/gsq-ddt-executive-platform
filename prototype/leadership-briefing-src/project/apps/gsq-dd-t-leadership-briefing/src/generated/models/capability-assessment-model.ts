import type { DigitalPlatform } from './digital-platform-model';
import type { ManufacturingSite } from './manufacturing-site-model';

export const CapabilityAssessmentCapabilityDimensionKeyToLabel = {
  'Process': 'Process',
  'Technology': 'Technology',
  'Data': 'Data',
  'People': 'People',
  'Governance': 'Governance'
} as const;
export type CapabilityAssessmentCapabilityDimensionKey = keyof typeof CapabilityAssessmentCapabilityDimensionKeyToLabel;

export const CapabilityAssessmentMaturityLevelKeyToLabel = {
  'Initial': 'Initial',
  'Developing': 'Developing',
  'Defined': 'Defined',
  'Managed': 'Managed',
  'Optimized': 'Optimized'
} as const;
export type CapabilityAssessmentMaturityLevelKey = keyof typeof CapabilityAssessmentMaturityLevelKeyToLabel;

export interface CapabilityAssessment {
  /**
   * @displayName Capability Assessment ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Capability Assessment Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  capabilityAssessmentName: string;
  /**
   * @displayName Assessment Date
   * @validationRule Required for create/update operations
   */
  assessmentDate: string;
  /**
   * @displayName Assessment Note
   */
  assessmentNote?: string;
  /**
   * @displayName Capability Dimension
   * @validationRule Required for create/update operations
   */
  capabilityDimensionKey: CapabilityAssessmentCapabilityDimensionKey;
  /**
   * @displayName Digital Platform
   * @validationRule Required for create/update operations
   */
  digitalPlatform: Pick<DigitalPlatform, 'id' | 'digitalPlatformName'>;
  /**
   * @displayName Manufacturing Site
   * @validationRule Required for create/update operations
   */
  manufacturingSite: Pick<ManufacturingSite, 'id' | 'siteName'>;
  /**
   * @displayName Maturity Level
   * @validationRule Required for create/update operations
   */
  maturityLevelKey: CapabilityAssessmentMaturityLevelKey;
  /**
   * @displayName Score
   * @validationRule Required for create/update operations
   */
  score: number;
}

export const _CapabilityAssessment = 'CapabilityAssessment' as const;
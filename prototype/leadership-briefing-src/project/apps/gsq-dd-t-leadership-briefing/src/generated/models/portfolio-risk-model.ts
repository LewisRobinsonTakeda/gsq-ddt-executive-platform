import type { PortfolioInitiative } from './portfolio-initiative-model';

export const PortfolioRiskImpactKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High'
} as const;
export type PortfolioRiskImpactKey = keyof typeof PortfolioRiskImpactKeyToLabel;

export const PortfolioRiskLikelihoodKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High'
} as const;
export type PortfolioRiskLikelihoodKey = keyof typeof PortfolioRiskLikelihoodKeyToLabel;

export const PortfolioRiskStatusKeyToLabel = {
  'Open': 'Open',
  'Monitoring': 'Monitoring',
  'Mitigated': 'Mitigated',
  'Closed': 'Closed'
} as const;
export type PortfolioRiskStatusKey = keyof typeof PortfolioRiskStatusKeyToLabel;

export interface PortfolioRisk {
  /**
   * @displayName Portfolio Risk ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Risk Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  riskName: string;
  /**
   * @displayName Closed Date
   */
  closedDate?: string;
  /**
   * @displayName Impact
   * @validationRule Required for create/update operations
   */
  impactKey: PortfolioRiskImpactKey;
  /**
   * @displayName Likelihood
   * @validationRule Required for create/update operations
   */
  likelihoodKey: PortfolioRiskLikelihoodKey;
  /**
   * @displayName Mitigation Summary
   * @validationRule Required for create/update operations
   */
  mitigationSummary: string;
  /**
   * @displayName Portfolio Initiative
   * @validationRule Required for create/update operations
   */
  portfolioInitiative: Pick<PortfolioInitiative, 'id' | 'portfolioInitiativeName'>;
  /**
   * @displayName Risk Score
   * @validationRule Required for create/update operations
   */
  riskScore: number;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: PortfolioRiskStatusKey;
  /**
   * @displayName Target Resolution Date
   */
  targetResolutionDate?: string;
}

export const _PortfolioRisk = 'PortfolioRisk' as const;
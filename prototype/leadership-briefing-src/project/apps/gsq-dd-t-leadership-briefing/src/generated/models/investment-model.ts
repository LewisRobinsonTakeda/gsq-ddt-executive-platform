import type { PortfolioInitiative } from './portfolio-initiative-model';

export const InvestmentInvestmentCategoryKeyToLabel = {
  'Capital': 'Capital',
  'Operating': 'Operating',
  'Mixed': 'Mixed'
} as const;
export type InvestmentInvestmentCategoryKey = keyof typeof InvestmentInvestmentCategoryKeyToLabel;

export const InvestmentStatusKeyToLabel = {
  'Planned': 'Planned',
  'Approved': 'Approved',
  'Committed': 'Committed',
  'Spent': 'Spent'
} as const;
export type InvestmentStatusKey = keyof typeof InvestmentStatusKeyToLabel;

export interface Investment {
  /**
   * @displayName Investment ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Investment Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  investmentName: string;
  /**
   * @displayName Approved Amount
   * @validationRule Required for create/update operations
   */
  approvedAmount: number;
  /**
   * @displayName Currency Code
   * @validationRule Required for create/update operations
   */
  currencyCode: string;
  /**
   * @displayName Fiscal Year
   * @validationRule Required for create/update operations
   */
  fiscalYear: number;
  /**
   * @displayName Forecast Amount
   * @validationRule Required for create/update operations
   */
  forecastAmount: number;
  /**
   * @displayName Investment Category
   * @validationRule Required for create/update operations
   */
  investmentCategoryKey: InvestmentInvestmentCategoryKey;
  /**
   * @displayName Portfolio Initiative
   * @validationRule Required for create/update operations
   */
  portfolioInitiative: Pick<PortfolioInitiative, 'id' | 'portfolioInitiativeName'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: InvestmentStatusKey;
}

export const _Investment = 'Investment' as const;